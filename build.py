#!/usr/bin/env python3
"""Linuxverse build: regenerates sw.js and writes dist/ (zip, single-file preview, artifact page).

Usage:  python3 build.py
Bump VERSION in js/core.js before each release.
"""
import base64
import pathlib
import re
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent
DIST = ROOT / "dist"

SCRIPTS = re.findall(r'<script src="([^"]+)"></script>', (ROOT / "index.html").read_text())
STATIC = ["index.html", "manifest.webmanifest", "css/app.css", *SCRIPTS,
          "icons/icon.svg", "icons/icon-192.png", "icons/icon-512.png",
          "icons/icon-maskable-512.png", "icons/apple-touch-icon.png"]


def version() -> str:
    m = re.search(r"var VERSION = '([^']+)'", (ROOT / "js/core.js").read_text())
    if not m:
        raise SystemExit("VERSION not found in js/core.js")
    return m.group(1)


def write_sw(ver: str) -> None:
    files = ",\n  ".join(f"'./{f}'" for f in STATIC)
    sw = f"""/* Generated by build.py — do not edit by hand */
const CACHE = 'linuxverse-v{ver}';
const FILES = [
  './',
  {files}
];
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === location.origin) {{
    e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then(hit => hit || fetch(req).then(res => {{
      const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); return res;
    }}).catch(() => caches.match('./index.html'))));
  }} else if (/fonts\\.(googleapis|gstatic)\\.com$/.test(url.hostname)) {{
    e.respondWith(caches.open(CACHE).then(c => c.match(req).then(hit => {{
      const net = fetch(req).then(res => {{ c.put(req, res.clone()); return res; }}).catch(() => hit);
      return hit || net;
    }})));
  }}
}});
"""
    (ROOT / "sw.js").write_text(sw)


def data_uri(path: str) -> str:
    p = ROOT / path
    mime = "image/svg+xml" if p.suffix == ".svg" else "image/png"
    return f"data:{mime};base64," + base64.b64encode(p.read_bytes()).decode()


def inline_parts():
    html = (ROOT / "index.html").read_text()
    body = html.split("<!--BODY-->")[1].split("<!--/BODY-->")[0]
    body = re.sub(r'\s*<script src="[^"]+"></script>', "", body)
    css = (ROOT / "css/app.css").read_text()
    js = "\n".join((ROOT / s).read_text() for s in SCRIPTS)
    js = js.replace("</script", "<\\/script")
    return body.strip(), css, "window.LV_INLINE = true;\n" + js


def build():
    ver = version()
    write_sw(ver)
    DIST.mkdir(exist_ok=True)

    with zipfile.ZipFile(DIST / "linuxverse.zip", "w", zipfile.ZIP_DEFLATED) as z:
        for f in [*STATIC, "sw.js", "build.py", "README.md", ".gitignore", ".github/workflows/pages.yml", "icons/icon-maskable.svg"]:
            if (ROOT / f).exists():
                z.write(ROOT / f, f"linuxverse/{f}")
        for shot in sorted((ROOT / "docs/screenshots").glob("*.png")):
            z.write(shot, f"linuxverse/docs/screenshots/{shot.name}")

    body, css, js = inline_parts()
    fonts = ('<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Chakra+Petch:wght@500;600;700'
             '&family=IBM+Plex+Mono:wght@400;600&family=IBM+Plex+Sans:wght@400;600&display=swap">')
    single = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Linuxverse</title>
<meta name="theme-color" content="#0c1018">
<link rel="icon" href="{data_uri('icons/icon.svg')}">
<link rel="apple-touch-icon" href="{data_uri('icons/apple-touch-icon.png')}">
{fonts}
<style>
{css}
</style>
</head>
<body>
{body}
<script>
{js}
</script>
</body>
</html>
"""
    (DIST / "index.html").write_text(single)

    artifact = f"""<title>Linuxverse</title>
<meta name="claude:viewport-fit-sides" content="cover">
{fonts}
<style>
{css}
</style>
{body}
<script>
{js}
</script>
"""
    (DIST / "artifact.html").write_text(artifact)
    print(f"Linuxverse v{ver}: sw.js, dist/linuxverse.zip, dist/index.html ({len(single)//1024} KB), dist/artifact.html")


if __name__ == "__main__":
    build()
